def write_admission_rules():
    headers = ["year", "school_id", "major_name_std", "rule_type", "rule_raw_text",
               "rule_structured_json", "source_id", "source_url", "source_page"]
    rows = []

    for year, src_id in [("2024", "SRC-2024-ZC"), ("2025", "SRC-2025-ZC"), ("2026", "SRC-2026-ZC")]:
        # Score formula
        rows.append([year, SCHOOL_ID, "", "score_formula",
                     "总分=公共课1+公共课2+专业课1+专业课2，满分600分",
                     '{"formula":"public1+public2+prof1+prof2","max_score":600}',
                     src_id, "", ""])

        # Public course requirement
        rows.append([year, SCHOOL_ID, "", "public_course_requirement",
                     "公共课须达到省考试院划定的公共课考试合格分数线",
                     '{"requirement":"pass_provincial_minimum"}',
                     src_id, "", ""])

        # Professional course requirement
        rows.append([year, SCHOOL_ID, "", "professional_course_requirement",
                     "专业课考试总分（专业课科目1+专业课科目2）不低于100分",
                     '{"requirement":"prof1+prof2>=100"}',
                     src_id, "", ""])

        # Ranking rule
        rows.append([year, SCHOOL_ID, "", "ranking_rule",
                     "按考试科目成绩总和从高分到低分排序，择优录取",
                     '{"method":"total_score_descending"}',
                     src_id, "", ""])

        # Tie break rule
        rows.append([year, SCHOOL_ID, "", "tie_break_rule",
                     "同分排序：专业课科目1>专业课科目2>大学语文/高等数学>英语",
                     '{"order":["prof1","prof2","public1","public2"]}',
                     src_id, "", ""])

        # Adjustment rule
        if year == "2026":
            adj_text = "若一志愿招生专业生源不均衡，依次进行A段专业内计划调整、A段专业间计划调整、B段专业间计划调整、A-B段间计划调整、外校A/B段生源调剂"
        else:
            adj_text = "若一志愿招生专业生源不均衡，将进行计划调整，具体按招生章程规定执行"
        rows.append([year, SCHOOL_ID, "", "adjustment_rule",
                     adj_text,
                     '{"method":"multi_step_adjustment"}',
                     src_id, "", ""])

    append_csv("admission_rules.csv", headers, rows)


