def append_csv(filename, headers, rows):
    """Append rows to a CSV file with UTF-8 BOM encoding."""
    path = os.path.join(NORM_DIR, filename)
    with open(path, "a", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f)
        for row in rows:
            writer.writerow(row)
    print(f"  {filename}: appended {len(rows)} rows")


