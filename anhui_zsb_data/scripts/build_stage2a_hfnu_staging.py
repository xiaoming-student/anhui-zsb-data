def application_statistics_payload() -> dict[str, Any]:
    path = RAW_ROOT / "2024" / "HFNU" / "DOC-HFNU-2024-BMRS_parsed.txt"
    lines = [line.strip() for line in path.read_text(encoding="utf-8-sig").splitlines() if line.strip()]
    try:
        start = lines.index("序号")
        end = next(index for index, line in enumerate(lines[start:], start) if line.startswith("上一篇："))
    except (ValueError, StopIteration) as exc:
        raise StagingError("cannot locate 2024 BMRS table") from exc
    cells = lines[start:end]
    if cells[:4] != ["序号", "专业名称", "计划数", "报考人数"]:
        raise StagingError(f"unexpected BMRS header: {cells[:4]}")
    rows: list[dict[str, Any]] = []
    for offset in range(4, len(cells), 4):
        chunk = cells[offset : offset + 4]
        if len(chunk) != 4:
            raise StagingError(f"incomplete BMRS row: {chunk}")
        sequence, raw_major, plan, applicants = chunk
        if not sequence.isdigit() or not plan.isdigit() or not applicants.isdigit():
            raise StagingError(f"invalid BMRS row: {chunk}")
        match = re.match(r"^(.*?)[（(]([^()（）]+)[）)]$", raw_major)
        major = match.group(1).strip() if match else raw_major
        institution = match.group(2).strip() if match else ""
        row_key = f"{major}|{institution or '合肥师范学院'}"
        rows.append(
            {
                "major_name_raw": major,
                "training_institution_name_raw": institution,
                "plan_count_raw": int(plan),
                "applicant_count_raw": int(applicants),
                "qualified_count_raw": None,
                "admitted_count_raw": None,
                "source_locator": {
                    "asset_id": "ASSET-HFNU-2024-BMRS-HTML",
                    "table": 1,
                    "row": int(sequence),
                    "row_key": row_key,
                },
            }
        )
    if len(rows) != 30:
        raise StagingError(f"expected 30 BMRS rows, found {len(rows)}")
    return metadata(2024, "SRC-HFNU-2024-BMRS", rows, "deterministic_parse_of_reviewed_official_html_text")


def syllabus_and_books_payloads(year: int) -> tuple[dict[str, Any], dict[str, Any]]:
    full_text, sections = parse_sections(year)
    exam_rows = load_json(STAGING_ROOT / str(year) / "exam_subjects.json")["data"]
    section_by_major: dict[str, Section] = {}
    for section in sections:
        for major in section.majors:
            if major in section_by_major:
                raise StagingError(f"duplicate DG major section: {year} {major}")
            section_by_major[major] = section
    expected_majors = {str(row["major_name_raw"]) for row in exam_rows}
    if set(section_by_major) != expected_majors:
        raise StagingError(
            f"DG major coverage differs from exam staging for {year}: "
            f"missing={sorted(expected_majors-set(section_by_major))}, "
            f"extra={sorted(set(section_by_major)-expected_majors)}"
        )

    syllabus_rows: list[dict[str, Any]] = []
    book_rows: list[dict[str, Any]] = []
    pdf_asset_id = f"ASSET-HFNU-{year}-DG-PDF"
    for exam_row in exam_rows:
        major = str(exam_row["major_name_raw"])
        subjects = [normalize_subject(str(exam_row["professional_subject_1"])), normalize_subject(str(exam_row["professional_subject_2"]))]
        section = section_by_major[major]
        if section.subjects != subjects:
            raise StagingError(f"DG subject pair mismatch: {year} {major}: {section.subjects} != {subjects}")

        entries = reference_entries(section)
        parsed_books: list[dict[str, Any]] = []
        for entry, absolute_position in entries:
            title = book_title(entry).strip()
            if not title or re.fullmatch(r"[\d.。]+", title) or len(normalize_compact(title)) < 2:
                continue
            assigned = assigned_subjects(subjects, title, entry)
            if not assigned:
                continue
            for subject in assigned:
                parsed_books.append(
                    {
                        "subject": subject,
                        "book_name_raw": title,
                        "author_raw": parse_author(entry, title),
                        "publisher_raw": parse_publisher(entry),
                        "edition_raw": parse_edition(entry),
                        "isbn_raw": parse_isbn(entry),
                        "entry_raw": entry,
                        "reference_key_raw": normalize_compact(entry),
                        "page": page_number(full_text, absolute_position),
                    }
                )
        for subject in subjects:
            if not any(item["subject"] == subject for item in parsed_books):
                raise StagingError(f"no reference book mapped: {year} {major} {subject}")

        for subject_index, subject in enumerate(subjects):
            raw_text, absolute_start, absolute_end = subject_raw_text(section, subject_index)
            locator = {
                "asset_id": pdf_asset_id,
                "page": page_value(full_text, absolute_start, absolute_end),
                "section": subject,
                "row_key": f"{major}|{subject}",
            }
            syllabus_rows.append(
                {
                    "major_name_raw": major,
                    "subject_name_raw": subject,
                    "title_raw": f"《{subject}》考试大纲",
                    "raw_text": raw_text,
                    "source_locator": locator,
                }
            )
            seen_books: set[str] = set()
            for book in parsed_books:
                if book["subject"] != subject:
                    continue
                key = book["reference_key_raw"]
                if key in seen_books:
                    continue
                seen_books.add(key)
                book_rows.append(
                    {
                        "major_name_raw": major,
                        "subject_name_raw": subject,
                        "book_name_raw": book["book_name_raw"],
                        "author_raw": book["author_raw"],
                        "publisher_raw": book["publisher_raw"],
                        "edition_raw": book["edition_raw"],
                        "isbn_raw": book["isbn_raw"],
                        "entry_raw": book["entry_raw"],
                        "reference_key_raw": book["reference_key_raw"],
                        "source_locator": {
                            "asset_id": pdf_asset_id,
                            "page": book["page"],
                            "section": "参考书目",
                            "row_key": f"{major}|{subject}|{book['book_name_raw']}",
                        },
                    }
                )

    syllabus_rows.sort(key=lambda row: (row["major_name_raw"], row["subject_name_raw"]))
    book_rows.sort(key=lambda row: (row["major_name_raw"], row["subject_name_raw"], row["book_name_raw"], row["reference_key_raw"]))
    return (
        metadata(year, f"SRC-HFNU-{year}-DG", syllabus_rows, "deterministic_parse_of_reviewed_official_pdf_text"),
        metadata(year, f"SRC-HFNU-{year}-DG", book_rows, "deterministic_parse_of_reviewed_official_pdf_text"),
    )


def expected_files() -> dict[Path, bytes]:
    files: dict[Path, bytes] = {
        STAGING_ROOT / "2026" / "admission_scores.json": dump_bytes(admission_scores_payload()),
        STAGING_ROOT / "2024" / "application_statistics.json": dump_bytes(application_statistics_payload()),
    }
    for year in (2024, 2025, 2026):
        syllabus, books = syllabus_and_books_payloads(year)
        files[STAGING_ROOT / str(year) / "syllabus.json"] = dump_bytes(syllabus)
        files[STAGING_ROOT / str(year) / "reference_books.json"] = dump_bytes(books)
    return files


def apply() -> int:
    files = expected_files()
    for path, data in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    print(f"Stage 2A HFNU staging: PASS ({len(files)} files written)")
    return 0


def check() -> int:
    errors: list[str] = []
    files = expected_files()
    for path, expected in files.items():
        if not path.is_file():
            errors.append(f"missing staging file: {path.relative_to(ROOT)}")
        elif path.read_bytes() != expected:
            errors.append(f"staging bytes differ from deterministic extraction: {path.relative_to(ROOT)}")
    if errors:
        print("Stage 2A HFNU staging check: FAIL")
        for error in errors:
            print(f"- {error}")
        return 1
    print(f"Stage 2A HFNU staging check: PASS ({len(files)} files)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--apply", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        return apply() if args.apply else check()
    except (StagingError, OSError, json.JSONDecodeError, KeyError, ValueError) as exc:
        print(f"Stage 2A HFNU staging: FAIL\n- {exc}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
