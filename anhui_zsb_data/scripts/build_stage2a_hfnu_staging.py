class StagingError(RuntimeError):
    pass


@dataclass
class Section:
    majors: list[str]
    subjects: list[str]
    header: str
    segment: str
    absolute_start: int
    absolute_end: int
    full_text: str


def load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def dump_bytes(value: Any) -> bytes:
    return (json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8")


def normalize_compact(value: str) -> str:
    return re.sub(r"\s+", "", value).replace("（", "(").replace("）", ")")


def normalize_subject(value: str) -> str:
    compact = normalize_compact(value)
    return SUBJECT_ALIASES.get(compact, compact)


def page_number(text: str, absolute_position: int) -> int:
    return text.count("\f", 0, absolute_position) + 1


def page_value(text: str, start: int, end: int) -> int | str:
    first = page_number(text, start)
    last = page_number(text, max(start, end - 1))
    return first if first == last else f"{first}-{last}"


def parse_sections(year: int) -> tuple[str, list[Section]]:
    path = RAW_ROOT / str(year) / "HFNU" / f"DOC-HFNU-{year}-DG.txt"
    text = path.read_text(encoding="utf-8-sig")
    starts = [match.start() for match in re.finditer("【考试科目】", text)]
    header_starts = [text.rfind("\f", 0, start) + 1 for start in starts]
    sections: list[Section] = []
    for index, start in enumerate(starts):
        header_start = header_starts[index]
        end = header_starts[index + 1] if index + 1 < len(starts) else len(text)
        header_lines = []
        for raw in text[header_start:start].splitlines():
            line = raw.strip()
            if not line or re.fullmatch(r"\d+", line):
                continue
            header_lines.append(line)
        header = normalize_compact("".join(header_lines))
        if not header.endswith("专业"):
            raise StagingError(f"cannot parse DG section header for {year}: {header!r}")
        majors = [item for item in header[:-2].split("、") if item]
        segment = text[start:end]
        if "【考试范围】" not in segment:
            raise StagingError(f"DG section has no exam range: {year} {header}")
        exam_block = segment.split("【考试范围】", 1)[0]
        subjects = [normalize_subject(item) for item in re.findall(r"《([^》]+)》", exam_block)]
        if len(subjects) != 2:
            raise StagingError(f"DG section must have two subjects: {year} {header}: {subjects}")
        sections.append(Section(majors, subjects, header, segment, start, end, text))
    return text, sections


def find_heading(body: str, subject: str) -> int | None:
    variants = HEADING_ALIASES.get(subject, (subject,))
    for variant in variants:
        pattern = r"《\s*" + r"\s*".join(re.escape(char) for char in variant) + r"\s*》"
        match = re.search(pattern, body)
        if match:
            return match.start()
    for variant in variants:
        match = re.search(re.escape(variant), body)
        if match:
            return match.start()
    return None


def subject_raw_text(section: Section, subject_index: int) -> tuple[str, int, int]:
    marker = section.segment.index("【考试范围】") + len("【考试范围】")
    body = section.segment[marker:]
    starts = [find_heading(body, subject) for subject in section.subjects]
    if starts[0] is None:
        starts[0] = 0
    if starts[1] is None or int(starts[1]) - int(starts[0]) < 80:
        local_start = 0
        local_end = len(body)
    elif subject_index == 0:
        local_start = int(starts[0])
        local_end = int(starts[1])
    else:
        local_start = int(starts[1])
        local_end = len(body)
    raw = body[local_start:local_end].strip()
    if len(raw) < 40:
        raw = body.strip()
        local_start = 0
        local_end = len(body)
    absolute_start = section.absolute_start + marker + local_start
    absolute_end = section.absolute_start + marker + local_end
    return raw, absolute_start, absolute_end


def reference_entries(section: Section) -> list[tuple[str, int]]:
    results: list[tuple[str, int]] = []
    marker_matches = list(re.finditer("【参考书目】", section.segment))
    exact_subjects = {normalize_compact(f"《{item}》") for item in section.subjects}
    for marker_index, marker in enumerate(marker_matches):
        region_start = marker.end()
        region_end = marker_matches[marker_index + 1].start() if marker_index + 1 < len(marker_matches) else len(section.segment)
        region = section.segment[region_start:region_end]
        current: list[str] = []
        current_position: int | None = None
        offset = 0
        for raw_line in region.splitlines(keepends=True):
            stripped = raw_line.replace("\f", "").strip()
            line_position = section.absolute_start + region_start + offset
            offset += len(raw_line)
            if not stripped or re.fullmatch(r"\d+", stripped):
                continue
            if normalize_compact(stripped) in exact_subjects:
                break
            if re.match(r"^\d+[.、．]", stripped):
                if current:
                    results.append((" ".join(current), int(current_position)))
                current = [re.sub(r"^\d+[.、．]\s*", "", stripped)]
                current_position = line_position
                continue
            if current:
                current.append(stripped)
                continue
            if "出版社" in stripped or "ISBN" in stripped or "《" in stripped or stripped.startswith("http"):
                current = [stripped]
                current_position = line_position
                continue
            if re.match(r"^(第[一二三四五六七八九十]+章|考核要点|考试时间|考试内容)", stripped):
                break
        if current:
            results.append((" ".join(current), int(current_position)))
    deduped: list[tuple[str, int]] = []
    seen: set[str] = set()
    for entry, position in results:
        key = normalize_compact(entry)
        if key not in seen:
            seen.add(key)
            deduped.append((entry, position))
    return deduped


def book_title(entry: str) -> str:
    matches = re.findall(r"《([^》]+)》", entry)
    if matches:
        title = matches[0].rstrip("》").strip()
        if not re.fullmatch(r"[\d.。]+", title):
            return title
    compact = normalize_compact(entry)
    for hint in sorted(BOOK_TITLE_HINTS, key=len, reverse=True):
        if normalize_compact(hint) in compact:
            return hint
    candidate = re.sub(r"^\d+[.、．]\s*", "", entry).split("，", 1)[0].split(",", 1)[0].strip()
    return candidate


AUTHOR_ROLE_RE = re.compile(r"(编著|主编|教材编写组|编写组|合著|著|编|译)")
GENERIC_AUTHOR_PREFIXES = (
    "马克思主义理论研究和建设工程重点教材",
    "马克思主义理论研究和建设工程",
)


def _flexible_text_pattern(value: str) -> str:
    return r"\s*".join(re.escape(char) for char in value if not char.isspace())


def _clean_author_candidate(value: str) -> str:
    value = re.sub(r"\s+", " ", value).strip(" ，,。.；;:：·")
    value = re.sub(
        r"^[（(]\s*(?:第?\s*[一二三四五六七八九十0-9]+\s*版|马工程)\s*[）)]",
        "",
        value,
    )
    value = value.strip(" ，,。.；;:：·")
    value = re.sub(
        r"^(?:上册|下册|第?\s*[一二三四五六七八九十0-9]+\s*版)\s*[，,。.]*",
        "",
        value,
    )
    value = re.split(
        r"[，,。.]+\s*(?=(?:第?\s*[一二三四五六七八九十0-9]+\s*版|19\d{2}|20\d{2}|北京(?:\s*[:：])?|ISBN\s*[:：]))",
        value,
        maxsplit=1,
    )[0]
    value = re.split(
        r"(?=19\d{2}|20\d{2}|北京(?:\s*[:：])?|ISBN\s*[:：])",
        value,
        maxsplit=1,
    )[0]
    value = re.sub(r"\s+(?=(?:编著|主编|教材编写组|编写组|合著|著|编|译))", "", value)
    return value.strip(" ，,。.；;:：·")


def _is_author_candidate(value: str) -> bool:
    compact = re.sub(r"\s+", "", value)
    if not compact or len(compact) > 60:
        return False
    if any(compact.startswith(prefix) for prefix in GENERIC_AUTHOR_PREFIXES):
        return False
    if compact in {"马工程", "上册", "下册"} or re.fullmatch(
        r"第?[一二三四五六七八九十0-9]+版", compact
    ):
        return False
    if "出版社" in compact or "http" in compact.lower():
        return False
    if AUTHOR_ROLE_RE.search(compact):
        return True
    if re.fullmatch(
        r"[\u4e00-\u9fff·]{2,12}(?:(?:\s+|[、，,])[\u4e00-\u9fff·]{2,12}){0,7}",
        value,
    ):
        return True
    if re.fullmatch(r"[\u4e00-\u9fff]{2,20}大学", compact):
        return True
    return False


def parse_author(entry: str, title: str) -> str:
    """Extract only an explicitly printed author/editor expression.

    The source PDFs use several bibliographic styles and contain visual line
    wrapping.  This parser never looks up or infers a person: it only returns a
    bounded substring adjacent to the printed title when that substring is an
    explicit name list, university, or editorial-role expression.
    """

    normalized = re.sub(r"\s+", " ", entry).strip()
    title_pattern = _flexible_text_pattern(title)
    explicit_group = re.search(
        r"《\s*" + title_pattern + r"\s*》\s*编写组", normalized
    )
    if explicit_group:
        return re.sub(r"\s+", "", explicit_group.group(0))

    match = re.search(r"《\s*" + title_pattern + r"\s*》", normalized)
    if not match:
        match = re.search(title_pattern, normalized)
    if not match:
        return ""

    before = _clean_author_candidate(normalized[: match.start()])
    if _is_author_candidate(before):
        return before

    after = normalized[match.end() :]
    after = re.sub(r"^\s*(?:[（(][^）)]{0,40}[）)]\s*)+", "", after)
    after = re.sub(
        r"^\s*(?:上册|下册|第?\s*[一二三四五六七八九十0-9]+\s*版)\s*",
        "",
        after,
    )
    after = after.lstrip(" ，,。.；;:：·")
    publisher = re.search(r"[\u4e00-\u9fffA-Za-z·\s]+出\s*版\s*社", after)
    if publisher:
        after = after[: publisher.start()]

    candidate = _clean_author_candidate(after)
    if _is_author_candidate(candidate):
        return candidate
    for part in re.split(r"[，,。.]+", after):
        candidate = _clean_author_candidate(part)
        if _is_author_candidate(candidate):
            return candidate
    return ""


def parse_publisher(entry: str) -> str:
    compact = re.sub(r"\s+", "", entry)
    matches = re.findall(r"([\u4e00-\u9fffA-Za-z·]+出版社)", compact)
    return matches[-1] if matches else ""


def parse_edition(entry: str) -> str:
    match = re.search(r"(第\s*[一二三四五六七八九十0-9]+\s*版|[一二三四五六七八九十]+版)", entry)
    return re.sub(r"\s+", "", match.group(1)) if match else ""


def parse_isbn(entry: str) -> str:
    match = re.search(r"ISBN\s*[:：]?\s*([0-9Xx-]+)", entry, re.I)
    return match.group(1) if match else ""


def assigned_subjects(subjects: list[str], title: str, entry: str) -> list[str]:
    compact = normalize_compact(title + " " + entry)
    assigned: list[str] = []
    for subject in subjects:
        rules = BOOK_RULES.get(subject)
        if not rules:
            raise StagingError(f"no book assignment rules for subject: {subject}")
        if any(normalize_compact(rule) in compact for rule in rules):
            assigned.append(subject)
    return assigned


